  static AppLanguage byName(String name) {
    for (final AppLanguage language in all) {
      if (language.name == name) {
        return language;
      }
    }
    return all.firstWhere((AppLanguage language) => language.code == 'en');
  }

  static String lookupKey(AppLanguage language) {
    if (language.scriptCode != null) {
      return '${language.code}_${language.scriptCode}';
    }
    return language.code;
  }

  static List<Locale> get supportedLocales {
    return all.map((AppLanguage language) => language.locale).toList();
  }
