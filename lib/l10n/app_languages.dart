class AppLanguage {
  const AppLanguage({
    required this.name,
    required this.code,
    this.scriptCode,
    this.isRtl = false,
  });

  final String name;
  final String code;
  final String? scriptCode;
  final bool isRtl;

  Locale get locale => Locale.fromSubtags(
        languageCode: code,
        scriptCode: scriptCode,
      );
}

